/* =====================================================================
   اسکیمای mes — گام ۱۹: FRM-ME-02 «روش ساخت»

   پیش‌نیاز: گام‌های قبل تا mes_frm_me01 (کتابخانه‌ی عملیات)، ساختار محصول (گام ۱۰).
   یادداشت ALM: «ویرایشگر گرافیکی نمای دوم همین فرم است، نه فرم مستقل».

   نسخه‌ی قبل روش ساخت را در mfr.RoutingMaster، RoutingProductStructureAssignment، RoutingOperation و
   RoutingOperationOutput نگه می‌داشت؛ هر چهار با همان نام و فیلدها آمده‌اند:
     mes.RoutingMaster                     همان + IsTemplate، TemplateRoutingId (الگو و اشتقاق، F-ME-017)،
                                           IsTollManufacturing، CustomerPartyId، CustomerTitle (کارمزدی دریافتی، F-ME-019).
                                           نسخه همان VersionId قدیم است (← mes.ProductionRevision)، با ValidFromDate/ValidToDate (F-ME-009).
                                           MeasureUnitId این‌جا NULL پذیر است (واحد از کالای اصلی می‌آید).
     mes.RoutingProductStructureAssignment همان — روش به یک یا چند ساختار/محصول (F-ME-008)
     mes.RoutingOperation                  همان + ResourceGroupId؛ WorkCenterId این‌جا NULL پذیر است (منبع می‌تواند گروه منبع باشد
                                           یا از کتابخانه به ارث برسد). AllocationPercent قدیم = سهم‌بری عملیات موازی (F-ME-011).
     mes.RoutingOperationOutput            همان + RoutingOperationId — خروجی هر عملیات (برای کنترل «مسیر بدون خروجی»)
     mes.RoutingOperationLink              جدید — یال‌های گراف عملیات با سهم‌بری و هم‌پوشانی (F-ME-011، 013، 015)
     mes.RoutingOperationAlternative       جدید — عملیات جایگزین با شرط انتخاب (F-ME-012)
   نسخه‌ی قبل گراف نداشت و ترتیب فقط با Sequence بود.

   فرض‌ها و کدهای موقت:
     RoutingMasterStatusCode  1 = پیش‌نویس، 2 = در گردش تأیید، 3 = تأییدشده، 4 = منسوخ
     RoutingMethodCode        1 = تک‌مرحله‌ای، 2 = چندمرحله‌ای (F-ME-010) — معنای این فیلد در نسخه‌ی قبل منتظر تأیید
     ProductionTypeCode       1 = بچی/گسسته، 2 = پیوسته (گام ME-09) — معنای این فیلد در نسخه‌ی قبل منتظر تأیید
     OverlapTypeCode          1 = بدون هم‌پوشانی، 2 = پس از مقدار، 3 = پس از زمان (دقیقه)
     SelectionRuleCode        1 = بازه‌ی مقدار سفارش، 2 = در دسترس نبودن منبع اصلی، 3 = انتخاب کاربر، 4 = کمترین هزینه، 5 = کمترین زمان
     ReceiveOutputTypeCode    1 = اصلی، 2 = همزاد، 3 = جانبی، 4 = ضایعات، 5 = بازیافتی، 6 = نیمه‌ساخته‌ی بین‌مرحله‌ای
     MsrOrEstCode             1 = اندازه‌گیری‌شده، 2 = تخمینی

   فاز اول: F-ME-008 تا 013، 015 (نمایش گراف)، 016، 017، 018، 019. عملیات شرطی (014، مهم) نیامده.
   ویرایش گرافیکی با درگ‌اند‌دراپ اقدام نوشتنی است و با ثبت و ویرایش می‌آید. این اسکریپت idempotent است.
   ===================================================================== */

