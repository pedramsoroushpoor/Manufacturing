CREATE OR ALTER PROCEDURE mes.GetRoutings
  @CompanyId BIGINT
AS
BEGIN
  SET NOCOUNT ON;
  SELECT CAST(r.Id AS INT) AS RoutingId, r.Number AS Code, r.Name AS Title, v.Number AS VersionCode, CAST(r.VersionId AS INT) AS VersionId,
         r.ProductionTypeCode, r.RoutingMethodCode, r.RoutingBatchSize, r.MinBatchSize, r.MaxBatchSize, r.ValidFromDate, r.ValidToDate,
         r.RoutingMasterStatusCode AS StatusCode, CAST(r.ProductionLineId AS INT) AS LineId, l.Name AS LineTitle,
         r.IsTemplate, CAST(r.TemplateRoutingId AS INT) AS TemplateRoutingId, tp.Number + N' — ' + tp.Name AS TemplateTitle,
         r.IsTollManufacturing, r.CustomerTitle, r.Description,
         (SELECT TOP (1) p.MeasureUnitTitle FROM mes.RoutingProductStructureAssignment a
            JOIN mes.ProductStructureMaster m ON m.ProductStructureId = a.ProductStructureId AND m.IsMainProduct = 1 AND m.IsDeleted = 0
            JOIN mes.Product p ON p.Id = m.ProductId WHERE a.RoutingId = r.Id AND a.IsDeleted = 0) AS UnitTitle,
         (SELECT STRING_AGG(x.Code, N'، ') FROM (SELECT DISTINCT p.Number + N' ' + p.Name AS Code FROM mes.RoutingProductStructureAssignment a
            JOIN mes.ProductStructureMaster m ON m.ProductStructureId = a.ProductStructureId AND m.IsMainProduct = 1 AND m.IsDeleted = 0
            JOIN mes.Product p ON p.Id = m.ProductId WHERE a.RoutingId = r.Id AND a.IsDeleted = 0) x) AS Products,
         (SELECT COUNT(*) FROM mes.RoutingOperation o WHERE o.RoutingId = r.Id AND o.IsDeleted = 0) AS OperationCount
  FROM mes.RoutingMaster r
  LEFT JOIN mes.ProductionRevision v ON v.Id = r.VersionId
  LEFT JOIN mes.ProductionLine l ON l.Id = r.ProductionLineId
  LEFT JOIN mes.RoutingMaster tp ON tp.Id = r.TemplateRoutingId
  WHERE r.CompanyId = @CompanyId AND r.IsDeleted = 0
  ORDER BY r.IsTemplate DESC, r.Number, v.Number;
END
GO

CREATE OR ALTER PROCEDURE mes.GetRoutingAssignments
  @CompanyId BIGINT
AS
BEGIN
  SET NOCOUNT ON;
  SELECT CAST(a.Id AS INT) AS AssignmentId, CAST(a.RoutingId AS INT) AS RoutingId, CAST(a.ProductStructureId AS INT) AS StructureId,
         s.Number AS StructureCode, s.Name AS StructureTitle, p.Number AS ProductCode, p.Name AS ProductTitle, CAST(p.Id AS INT) AS ProductId,
         m.Quantity AS StructureQuantity, p.MeasureUnitTitle AS UnitTitle, a.YieldPercent, a.Description
  FROM mes.RoutingProductStructureAssignment a
  JOIN mes.ProductStructure s ON s.Id = a.ProductStructureId
  LEFT JOIN mes.ProductStructureMaster m ON m.ProductStructureId = s.Id AND m.IsMainProduct = 1 AND m.IsDeleted = 0
  LEFT JOIN mes.Product p ON p.Id = m.ProductId
  WHERE a.CompanyId = @CompanyId AND a.IsDeleted = 0
  ORDER BY a.RoutingId, s.Number;
END
GO

/* عملیات روش‌ها؛ منبع اگر در روش خالی باشد از منبع اصلی کتابخانه به ارث می‌رسد (ResourceSource = 2). */
CREATE OR ALTER PROCEDURE mes.GetRoutingOperations
  @CompanyId BIGINT
AS
BEGIN
  SET NOCOUNT ON;
  SELECT CAST(o.Id AS INT) AS RoutingOperationId, CAST(o.RoutingId AS INT) AS RoutingId, o.Sequence, CAST(o.OperationId AS INT) AS OperationId,
         op.Number AS OperationCode, op.Name AS OperationTitle, op.OperationTypeCode AS NatureCode,
         COALESCE(rg.Number + N' — ' + rg.Name, w.Number + N' — ' + w.Name + N' (' + l.Name + N')', lib.Title) AS ResourceTitle,
         CASE WHEN o.WorkCenterId IS NOT NULL OR o.ResourceGroupId IS NOT NULL THEN 1 WHEN lib.Title IS NOT NULL THEN 2 ELSE 0 END AS ResourceSource,
         o.AllocationPercent, o.YieldPercent, o.IsOutsourcing, o.Description
  FROM mes.RoutingOperation o
  JOIN mes.ProductionOperation op ON op.Id = o.OperationId
  LEFT JOIN mes.WorkCenter w ON w.Id = o.WorkCenterId
  LEFT JOIN mes.ProductionLine l ON l.Id = w.ProductionLineId
  LEFT JOIN mes.ResourceGroup rg ON rg.Id = o.ResourceGroupId
  OUTER APPLY (SELECT TOP (1) COALESCE(g2.Number + N' — ' + g2.Name, w2.Number + N' — ' + w2.Name + N' (' + l2.Name + N')') AS Title
               FROM mes.ProductionOperationResource pr
               LEFT JOIN mes.ResourceGroup g2 ON g2.Id = pr.ResourceGroupId
               LEFT JOIN mes.WorkCenter w2 ON w2.Id = pr.WorkCenterId
               LEFT JOIN mes.ProductionLine l2 ON l2.Id = w2.ProductionLineId
               WHERE pr.ProductionOperationId = o.OperationId AND pr.IsDeleted = 0
               ORDER BY pr.IsPrimary DESC, pr.Priority) lib
  WHERE o.CompanyId = @CompanyId AND o.IsDeleted = 0
  ORDER BY o.RoutingId, o.Sequence;
END
GO

CREATE OR ALTER PROCEDURE mes.GetRoutingLinks
  @CompanyId BIGINT
