CREATE OR ALTER PROCEDURE mes.GetRoutingAlternatives
  @CompanyId BIGINT
AS
BEGIN
  SET NOCOUNT ON;
  SELECT CAST(a.RoutingOperationId AS INT) AS RoutingOperationId, CAST(o.RoutingId AS INT) AS RoutingId, o.Sequence,
         op.Number + N' — ' + op.Name AS MainOperation, alt.Number + N' — ' + alt.Name AS AlternativeOperation, alt.OperationTypeCode AS AlternativeNatureCode,
         COALESCE(rg.Number + N' — ' + rg.Name, w.Number + N' — ' + w.Name + N' (' + l.Name + N')') AS ResourceTitle,
         a.SelectionRuleCode, a.FromQuantity, a.ToQuantity, a.Priority, a.Description
  FROM mes.RoutingOperationAlternative a
  JOIN mes.RoutingOperation o ON o.Id = a.RoutingOperationId
  JOIN mes.ProductionOperation op ON op.Id = o.OperationId
  JOIN mes.ProductionOperation alt ON alt.Id = a.AlternativeOperationId
  LEFT JOIN mes.WorkCenter w ON w.Id = a.WorkCenterId
  LEFT JOIN mes.ProductionLine l ON l.Id = w.ProductionLineId
  LEFT JOIN mes.ResourceGroup rg ON rg.Id = a.ResourceGroupId
  WHERE a.CompanyId = @CompanyId AND a.IsDeleted = 0
  ORDER BY o.RoutingId, o.Sequence, a.Priority;
END
GO

CREATE OR ALTER PROCEDURE mes.GetRoutingOutputs
  @CompanyId BIGINT
AS
BEGIN
  SET NOCOUNT ON;
  SELECT CAST(x.Id AS INT) AS OutputId, CAST(o.RoutingId AS INT) AS RoutingId, CAST(x.RoutingOperationId AS INT) AS RoutingOperationId,
         x.FromOperationSequence, x.ToOperationSequence, CAST(x.OuputProductId AS INT) AS ProductId, p.Number AS ProductCode, p.Name AS ProductTitle,
         p.MeasureUnitTitle AS UnitTitle, x.ReceiveOutputTypeCode, x.IsMainOutputProduct, x.IsDeliverableProduct, x.Quantity, x.YieldPercent, x.Description
  FROM mes.RoutingOperationOutput x
  JOIN mes.RoutingOperation o ON o.Id = x.RoutingOperationId
  JOIN mes.Product p ON p.Id = x.OuputProductId
  WHERE x.CompanyId = @CompanyId AND x.IsDeleted = 0
  ORDER BY o.RoutingId, x.FromOperationSequence, x.ReceiveOutputTypeCode;
END
GO

